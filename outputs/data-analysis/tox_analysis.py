# Identify individual shutdown events (runs of NaN or sub-threshold)
def find_off_periods(df, outlet_col):
    """Return list of (start, end, duration_hrs) for contiguous off/cold periods."""
    is_off = df[outlet_col].isna() | (df[outlet_col] < DESTRUCT_THRESH_F)
    periods = []
    in_off = False
    start_idx = None
    for i, v in enumerate(is_off):
        if v and not in_off:
            in_off = True
            start_idx = i
        elif not v and in_off:
            in_off = False
            dur = i - start_idx
            periods.append((df['time'].iloc[start_idx], df['time'].iloc[i-1], dur))
    if in_off:
        dur = len(df) - start_idx
        periods.append((df['time'].iloc[start_idx], df['time'].iloc[-1], dur))
    return periods

